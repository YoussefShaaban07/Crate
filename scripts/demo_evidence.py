"""
Reproducible evidence that the two advanced features actually do something.

    python -m scripts.demo_evidence

Part A shows the RAG layer changing the ranking: for each golden case, the songs
the rule scorer alone would have returned versus what the full pipeline returns.

Part B shows the guardrails firing: the same request is run twice, once normally
and once against a fake model that returns a hallucinated song id and a
hallucinated citation, so you can see exactly what gets caught.

Everything here runs offline and is deterministic, so the output below is
reproducible on any machine with no API key.
"""

from __future__ import annotations

import json

from src.evaluation import load_cases
from src.llm import LLMResult, offline_parse_profile
from src.logging_setup import setup_logging
from src.pipeline import RecommendationPipeline

RULE = "=" * 78


class HallucinatingLLM:
    """A fake model that invents a song and a citation, to trip the guardrails."""

    mode = "claude"
    online = True

    def parse_profile(self, query, context, genres, moods):
        return LLMResult(offline_parse_profile(query, genres, moods), "claude")

    def rerank(self, query, profile, candidates, context, k):
        real_id = candidates[0]["song"]["id"]
        return LLMResult(
            {
                "recommendations": [
                    {
                        "song_id": 9999,
                        "rationale": "A song that does not exist in the catalog.",
                        "evidence": ["rev-totally-made-up"],
                        "confidence": 0.99,
                    },
                    {
                        "song_id": real_id,
                        "rationale": "A real song, but citing a document that was never retrieved.",
                        "evidence": ["rev-also-invented"],
                        "confidence": 0.95,
                    },
                ],
                "caveat": "Generated by a deliberately hallucinating stub.",
            },
            "claude",
        )


def part_a_rag_ablation() -> None:
    print(RULE)
    print("PART A - Does retrieval change the ranking, or just decorate it?")
    print(RULE)
    print()
    print("Same parsed profile, two rankings: the rule scorer alone, and the full")
    print("RAG pipeline. If retrieval were decorative these columns would match.")
    print()

    pipeline = RecommendationPipeline(force_offline=True)
    changed = 0
    cases = load_cases()

    for case in cases:
        result = pipeline.run(case["query"], k=5)

        from src.recommender import recommend_songs

        rule_only = [
            row[0]["id"] for row in recommend_songs(result.profile, pipeline.songs, k=5)
        ]
        rag = result.top_song_ids
        differs = rag != rule_only
        changed += differs

        print(f"  {case['id']}")
        print(f"    rules only : {rule_only}")
        print(f"    with RAG   : {rag}   {'<-- CHANGED' if differs else '(same)'}")

    print()
    print(f"  Retrieval changed the ranking on {changed} of {len(cases)} cases "
          f"({changed / len(cases):.3f}).")
    print()


def part_b_guardrails() -> None:
    print(RULE)
    print("PART B - Do the guardrails catch a model that hallucinates?")
    print(RULE)
    print()

    query = "high energy music for the gym, nothing acoustic"
    print(f'Request: "{query}"')
    print()

    print("--- B1. Normal run (deterministic re-ranker) ---")
    clean = RecommendationPipeline(force_offline=True).run(query, k=3)
    for rec in clean.recommendations:
        print(f"  {rec.rank}. song {rec.song['id']:>2}  {rec.song['title']:<22} "
              f"cites {rec.evidence}")
    print(f"  guardrails: {json.dumps(clean.guardrails.to_dict())}")
    print()

    print("--- B2. Same request, model returns song 9999 and two invented doc ids ---")
    tripped = RecommendationPipeline(llm=HallucinatingLLM()).run(query, k=3)
    for rec in tripped.recommendations:
        print(f"  {rec.rank}. song {rec.song['id']:>2}  {rec.song['title']:<22} "
              f"cites {rec.evidence}")

    guard = tripped.guardrails
    print()
    print("  What the guardrails caught:")
    print(f"    songs dropped as not-in-candidate-pool : {guard.dropped_songs}")
    print(f"    citations stripped as never-retrieved  : {guard.invalid_citations}")
    print(f"    groundedness after stripping           : {guard.groundedness:.2f}")
    print(f"    fell back to deterministic logic       : {guard.fell_back}")
    print()
    print("  Note: the two guardrails run in order. enforce_candidates drops song")
    print("  9999 first, taking its citation 'rev-totally-made-up' with it, which is")
    print("  why only one invented citation reaches the citation counter.")
    print("  enforce_citations then strips 'rev-also-invented' from the surviving")
    print("  pick, leaving it with no support (groundedness 0.00). The list is still")
    print("  full because the pipeline topped it up from the blended order.")
    print()


def main() -> int:
    setup_logging(verbose=False)
    part_a_rag_ablation()
    part_b_guardrails()
    print(RULE)
    print("Reproduce with: python -m scripts.demo_evidence")
    print(RULE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
